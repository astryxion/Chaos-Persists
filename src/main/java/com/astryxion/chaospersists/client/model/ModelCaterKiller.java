        float newangle = 0.0f;
        float headoff = 0.0f;
        float zpi = 0.0f;
        float zdist = 0.0f;
        newangle = entity.getAttacking() != 0 ? Mth.cos((float)(ageInTicks * 1.7f * this.wingspeed)) * 3.1415927f * 0.07f : Mth.cos((float)(ageInTicks * 1.3f * this.wingspeed)) * 3.1415927f * 0.025f;
