        newangle = Mth.cos((float)(ageInTicks * 0.81f * this.wingspeed)) * 3.1415927f * 0.04f;
        this.seg3lbackspike.xRot = -0.977f + newangle;
        newangle = Mth.cos((float)(ageInTicks * 0.87f * this.wingspeed)) * 3.1415927f * 0.04f;
        this.seg3rbackspike.xRot = -0.977f + newangle;
        newangle = Mth.cos((float)(ageInTicks * 1.11f * this.wingspeed)) * 3.1415927f * 0.04f;
        this.seg3lbackspike.yRot = 0.28f + newangle;
